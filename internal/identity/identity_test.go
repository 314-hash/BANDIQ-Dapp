package identity

import (
	"os"
	"path/filepath"
	"testing"
)

func TestIdentityGenerationAndSigning(t *testing.T) {
	validWallet := "0x6d1537bEE4F1EE3f55F4BC9319Aa40252cd39133"

	// Test invalid wallet
	_, err := GenerateNewIdentity("invalid_wallet")
	if err == nil {
		t.Fatalf("expected error for invalid wallet, got nil")
	}

	// Test valid identity generation
	id, err := GenerateNewIdentity(validWallet)
	if err != nil {
		t.Fatalf("failed to generate identity: %v", err)
	}

	if id.NodeID == "" || len(id.NodeID) < 15 {
		t.Fatalf("unexpected node ID: %s", id.NodeID)
	}

	// Test signing and verification
	msg := []byte("bandiq-report-proof-payload")
	sig := id.Sign(msg)
	if !VerifySignature(id.PublicKey, msg, sig) {
		t.Fatalf("signature verification failed")
	}

	// Test tamper detection
	tamperedMsg := []byte("bandiq-report-tampered-payload")
	if VerifySignature(id.PublicKey, tamperedMsg, sig) {
		t.Fatalf("tampered message unexpectedly verified")
	}

	// Test hex signing and verification
	sigHex := id.SignHex(msg)
	pubHex := id.PublicKeyHex()
	if !VerifySignatureHex(pubHex, msg, sigHex) {
		t.Fatalf("hex signature verification failed")
	}
}

func TestIdentityPersistence(t *testing.T) {
	tmpDir, err := os.MkdirTemp("", "bandiq-id-test-*")
	if err != nil {
		t.Fatalf("failed to create temp dir: %v", err)
	}
	defer os.RemoveAll(tmpDir)

	keyFile := filepath.Join(tmpDir, "node_key.json")
	wallet := "0x6d1537bee4f1ee3f55f4bc9319aa40252cd39133"

	id1, err := GenerateNewIdentity(wallet)
	if err != nil {
		t.Fatalf("failed to generate id: %v", err)
	}

	if err := id1.SaveToFile(keyFile); err != nil {
		t.Fatalf("failed to save id to file: %v", err)
	}

	id2, err := LoadFromFile(keyFile)
	if err != nil {
		t.Fatalf("failed to load id from file: %v", err)
	}

	if id1.NodeID != id2.NodeID {
		t.Fatalf("loaded node ID mismatch: %s != %s", id1.NodeID, id2.NodeID)
	}
	if id1.OperatorWallet != id2.OperatorWallet {
		t.Fatalf("loaded wallet mismatch: %s != %s", id1.OperatorWallet, id2.OperatorWallet)
	}

	// Verify id2 can verify signature created by id1
	testMsg := []byte("check-persistence-signing")
	sig := id1.Sign(testMsg)
	if !VerifySignature(id2.PublicKey, testMsg, sig) {
		t.Fatalf("signature generated by original failed verification by loaded identity")
	}
}
