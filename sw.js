const CACHE_NAME = 'bandiq-depin-v2.1';
const ASSETS_TO_CACHE = [
  '/dashboard/',
  '/dashboard/index.html',
  '/dashboard/style.css',
  '/dashboard/app.js',
  '/dashboard/contracts.js',
  '/dashboard/bandiq_logo.jpg',
  '/dashboard/manifest.json'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(ASSETS_TO_CACHE).catch(() => {});
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // Only cache GET requests, skip RPC / API calls
  if (event.request.method !== 'GET' || event.request.url.includes('/rpc') || event.request.url.includes('node.sidrachain.com')) {
    return;
  }

  event.respondWith(
    caches.match(event.request).then((cachedResponse) => {
      if (cachedResponse) {
        // Fetch fresh copy in background
        fetch(event.request).then((networkResponse) => {
          if (networkResponse && networkResponse.status === 200) {
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, networkResponse));
          }
        }).catch(() => {});
        return cachedResponse;
      }
      return fetch(event.request);
    })
  );
});
